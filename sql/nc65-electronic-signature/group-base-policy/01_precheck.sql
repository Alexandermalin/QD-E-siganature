SELECT SYS_CONTEXT('USERENV','SESSION_USER') session_user,
       SYS_CONTEXT('USERENV','CURRENT_SCHEMA') current_schema,
       SYS_CONTEXT('USERENV','DB_UNIQUE_NAME') database_name
  FROM dual;
SELECT version_no, applied_at FROM qd_es_schema_version
 WHERE version_no IN ('1.1.0','1.1.0-RB','1.2.0','1.2.0-RB')
 ORDER BY version_no;
SELECT business_state, COUNT(*) request_count FROM qd_es_request
 WHERE business_state IN ('PENDING','READY','RUNNING') GROUP BY business_state;
SELECT table_name, column_name FROM user_tab_columns
 WHERE table_name IN ('QD_ES_BD_CONTROL','QD_ES_BD_POLICY')
    OR (table_name='QD_ES_NODE' AND column_name='GROUP_SCOPE_ID')
 ORDER BY table_name, column_id;

